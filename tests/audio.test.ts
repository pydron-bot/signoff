// The recordings: the slots every fighter and hit has, the files on disk
// listed in public/assets/audio/index.json (only known names), and the
// shot list in docs/AUDIO-TODO.md that says what's recorded so far.
// After adding recordings, `npm run audio:index` rewrites both.
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { describe, expect, it } from 'vitest';
import { HIT_SLOTS, HITS, Takes, VOICE_SLOTS, WIN_LINES, hitLayers, parseClip, voiceSlot } from '../src/audio/clips';
import { banter, scriptOf } from '../src/game/banter';
import { FIGHTERS } from '../src/sim';

const ROOT = new URL('../public/assets/audio/', import.meta.url).pathname;
const INDEX = path.join(ROOT, 'index.json');
const DOC = new URL('../docs/AUDIO-TODO.md', import.meta.url);
const START = '<!-- shots:start (generated by `npm run audio:index`; do not edit by hand) -->';
const END = '<!-- shots:end -->';
const ids = Object.keys(FIGHTERS);
const lines = (f: string) => scriptOf(f).map((l) => l.id);

function filesOnDisk(dir = ROOT, rel = ''): string[] {
  return readdirSync(dir).flatMap((n) => {
    const p = path.join(dir, n);
    const r = rel ? `${rel}/${n}` : n;
    return statSync(p).isDirectory() ? filesOnDisk(p, r) : n.endsWith('.m4a') ? [r] : [];
  });
}

/** The shot list: every file to record, and how many takes of each are in. */
function shotList(files: readonly string[]): string {
  const have = new Map<string, number>();
  for (const f of files) {
    const k = parseClip(f, ids, lines);
    if (k) have.set(k, (have.get(k) ?? 0) + 1);
  }
  const tick = (k: string, want: number) => {
    const n = have.get(k) ?? 0;
    return n >= want ? `✅ ${n}` : n ? `${n} of ${want}` : '–';
  };
  const out: string[] = [];
  const total = { want: 0, have: 0 };
  const count = (k: string, want: number) => {
    total.want += want;
    total.have += Math.min(want, have.get(k) ?? 0);
  };
  for (const f of Object.values(FIGHTERS)) {
    out.push(`\n#### ${f.name} (\`${f.id}/\`)\n`);
    out.push('| File | Takes | When it plays | Recorded |', '| --- | --- | --- | --- |');
    for (const s of VOICE_SLOTS) {
      const k = `${f.id}/${s.id}`;
      count(k, s.count);
      out.push(`| \`${s.id}_1.m4a\` … \`_${s.count}\` | ${s.count} | ${s.when} | ${tick(k, s.count)} |`);
    }
    out.push('', `Win lines (\`win_1\`, \`win_2\`): “${WIN_LINES[f.id][0]}” / “${WIN_LINES[f.id][1]}”`, '');
    out.push('| Cold open line | Says | Recorded |', '| --- | --- | --- |');
    for (const l of scriptOf(f.id)) {
      const k = `${f.id}/line_${l.id}`;
      count(k, 1);
      const to = l.to ? ` *(to ${FIGHTERS[l.to].name})*` : '';
      out.push(`| \`line_${l.id}.m4a\` | ${l.text}${to} | ${tick(k, 1)} |`);
    }
  }
  out.push(`\n#### Hits (\`${HITS}/\`, shared)\n`, '| File | Takes | When it plays | Recorded |', '| --- | --- | --- | --- |');
  for (const s of HIT_SLOTS) {
    const k = `${HITS}/${s.id}`;
    count(k, s.count);
    out.push(`| \`${s.id}_1.m4a\` … \`_${s.count}\` | ${s.count} | ${s.when} | ${tick(k, s.count)} |`);
  }
  out.unshift(`**Recorded so far: ${total.have} of ${total.want} files.**`);
  return out.join('\n');
}

describe('recordings', () => {
  it('a vocal cue finds its slot; the babble stays synthesised', () => {
    expect(voiceSlot('effort', 0.45)).toBe('effort_light');
    expect(voiceSlot('effort', 0.7)).toBe('effort_heavy');
    expect(voiceSlot('pain', 0.35)).toBe('pain_light');
    expect(voiceSlot('pain', 1)).toBe('pain_heavy');
    expect(voiceSlot('scream', 1)).toBe('scream');
    expect(voiceSlot('talk', 0.5)).toBeNull();
  });

  it('a hit is built from layers by weight, a prop replacing the snap', () => {
    expect(hitLayers(0, 'punch')).toEqual(['snap_punch', 'thud']);
    expect(hitLayers(2, 'kick')).toEqual(['snap_kick', 'thud', 'crunch']);
    expect(hitLayers(3, 'metal')).toEqual(['metal', 'thud', 'crunch', 'boom']);
    for (const w of [0, 1, 2, 3] as const) for (const l of hitLayers(w, 'blade')) expect(HIT_SLOTS.map((s) => s.id)).toContain(l);
  });

  it('reads file names into slots, and turns away names it does not know', () => {
    expect(parseClip('dale/shout_2.m4a', ids, lines)).toBe('dale/shout');
    expect(parseClip('hits/snap_punch_3.m4a', ids, lines)).toBe('hits/snap_punch');
    expect(parseClip('gus/line_reply_1.m4a', ids, lines)).toBe('gus/line_reply_1');
    expect(parseClip('margaret/line_to_dale.m4a', ids, lines)).toBe('margaret/line_to_dale');
    expect(parseClip('dale/shout.m4a', ids, lines)).toBeNull();
    expect(parseClip('dale/shout_0.m4a', ids, lines)).toBeNull();
    expect(parseClip('dale/yell_1.m4a', ids, lines)).toBeNull();
    expect(parseClip('nobody/shout_1.m4a', ids, lines)).toBeNull();
    expect(parseClip('dale/line_to_rox_1.m4a', ids, lines)).toBeNull();
    expect(parseClip('dale/shout_1.wav', ids, lines)).toBeNull();
  });

  it('never plays the same take twice running, and gets round to all of them', () => {
    const t = new Takes();
    let seed = 7;
    const rand = () => ((seed = (seed * 16807) % 2147483647) / 2147483647);
    let last = -1;
    const seen = new Set<number>();
    for (let k = 0; k < 60; k++) {
      const n = t.pick('dale/shout', 4, rand);
      expect(n).not.toBe(last);
      expect(n >= 0 && n < 4).toBe(true);
      seen.add(n);
      last = n;
    }
    expect(seen.size).toBe(4);
    expect(t.pick('x', 1, rand)).toBe(0);
  });

  it('every fighter has win lines, and every cold open line its own file', () => {
    for (const id of ids) {
      expect(WIN_LINES[id], id).toBeDefined();
      const l = lines(id);
      expect(new Set(l).size, id).toBe(l.length);
      for (const x of l) expect(parseClip(`${id}/line_${x}.m4a`, ids, lines), x).toBe(`${id}/line_${x}`);
    }
    // Whatever the cold open picks, its lines are in the speakers' scripts.
    for (const a of ids)
      for (const b of ids)
        for (let seed = 1; seed < 9; seed++) {
          for (const c of banter(a, b, seed).clips) {
            const [f, key] = c.split('/');
            expect(lines(f).map((x) => `line_${x}`), c).toContain(key);
          }
        }
  });

  it('index.json lists exactly the recordings on disk, each a known slot; the shot list is up to date', () => {
    const files = filesOnDisk().sort();
    for (const f of files) expect(parseClip(f, ids, lines), `${f} is not a name the game knows (docs/AUDIO-TODO.md)`).not.toBeNull();
    const doc = readFileSync(DOC, 'utf8');
    const a = doc.indexOf(START);
    const b = doc.indexOf(END);
    expect(a, 'shot list markers').toBeGreaterThanOrEqual(0);
    expect(b).toBeGreaterThan(a);
    const list = shotList(files);
    if (process.env.UPDATE_AUDIO) {
      writeFileSync(INDEX, `${JSON.stringify({ files }, null, 2)}\n`);
      writeFileSync(DOC, `${doc.slice(0, a + START.length)}\n${list}\n\n${doc.slice(b)}`);
      return;
    }
    expect(JSON.parse(readFileSync(INDEX, 'utf8')).files, 'public/assets/audio/index.json is out of date: run `npm run audio:index`').toEqual(files);
    expect(doc.slice(a + START.length, b).trim(), 'docs/AUDIO-TODO.md is out of date: run `npm run audio:index`').toBe(list.trim());
  });
});
