// docs/BLENDER-TODO.md lists every animation clip with its exact frame
// count and where its hits land, from the move data. This keeps it true:
// after changing moves, run `npm run docs:clips` to rewrite the table.
import { readFileSync, writeFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { FIGHTERS, type MoveData } from '../src/sim';
import { toFloat } from '../src/sim/fixed';

const DOC = new URL('../docs/BLENDER-TODO.md', import.meta.url);
const START = '<!-- clips:start (generated by `npm run docs:clips`; do not edit by hand) -->';
const END = '<!-- clips:end -->';

const m = (v: number) => toFloat(v).toFixed(2);

function hits(mv: MoveData): string {
  const parts = mv.hits.map((h) => `${h.frames[0]}–${h.frames[1]}: x ${m(h.box.x)}…${m(h.box.x + h.box.w)}, y ${m(h.box.y)}…${m(h.box.y + h.box.h)} (${h.height})`);
  for (const s of mv.spawns) parts.push(`${s.frame}: spawns projectile at x ${m(s.projectile.x)}, y ${m(s.projectile.y)}${s.projectile.delay ? ` (waits ${s.projectile.delay} frames)` : ''}`);
  if (mv.counter) parts.push(`${mv.counter.frames[0]}–${mv.counter.frames[1]}: counter stance; a strike read here plays \`${mv.counter.into}\``);
  if (mv.throwData) parts.push(`${mv.throwData.frames[0]}–${mv.throwData.frames[1]}: grab (reach ${m(mv.throwData.range)})`);
  if (mv.interactFrame) parts.push(`${mv.interactFrame}: kicks the prop`);
  if (mv.hidden) parts.push(`${mv.hidden[0]}–${mv.hidden[1]}: off screen`);
  if (mv.teleport) parts.push(`${mv.teleport.frame}: reappears ${mv.teleport.to === 'behind' ? 'behind the opponent' : 'far back'}`);
  if (mv.armor) parts.push(`${mv.armor[0]}–${mv.armor[1]}: armour (glows)`);
  if (parts.length > 3) return `${parts.slice(0, 2).join('; ')}; … ${parts.length} hits to ${mv.lastActive}`;
  return parts.join('; ') || 'no hit';
}

export function clipTable(): string {
  const rows: string[] = [];
  for (const f of Object.values(FIGHTERS)) {
    rows.push(`\n#### ${f.name} (\`${f.id}\`): ${Object.keys(f.moves).length} move clips\n`);
    rows.push('| Clip (= move id) | Name | Kind | Stance | Frames | Active frames and hitbox (metres, +x = forward, y = up from feet) |');
    rows.push('| --- | --- | --- | --- | --- | --- |');
    for (const mv of Object.values(f.moves)) {
      rows.push(`| \`${mv.id}\` | ${mv.name} | ${mv.kind} | ${mv.stance} | ${mv.total} | ${hits(mv)} |`);
    }
  }
  return rows.join('\n');
}

describe('Blender TODO', () => {
  it('lists every move clip exactly as the data has it', () => {
    const doc = readFileSync(DOC, 'utf8');
    const a = doc.indexOf(START);
    const b = doc.indexOf(END);
    expect(a, 'clip table markers').toBeGreaterThanOrEqual(0);
    expect(b).toBeGreaterThan(a);
    const table = clipTable();
    if (process.env.UPDATE_DOCS) {
      writeFileSync(DOC, `${doc.slice(0, a + START.length)}\n${table}\n\n${doc.slice(b)}`);
      return;
    }
    expect(doc.slice(a + START.length, b).trim(), 'docs/BLENDER-TODO.md is out of date: run `npm run docs:clips`').toBe(table.trim());
  });
});
